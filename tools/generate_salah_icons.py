#!/usr/bin/env python3
"""Regenerate SALAH's launcher, monochrome, and notification icons.

The adaptive foreground, themed monochrome layer and legacy WebP files are all
drawn from the same crescent/star geometry here.  Keep the vector path and the
raster output in one place so the launcher, themed icons and status bar cannot
drift into three different marks.

Run from the repository root:

    python3 tools/generate_salah_icons.py

Requires Pillow.  The generated XML and WebP files are checked in; this script is
only needed when the mark changes.
"""

from __future__ import annotations

import math
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"

# --- Geometry ---------------------------------------------------------------

# Adaptive foreground.  Android's adaptive icon safe zone is the central 66dp
# of a 108dp canvas, so every point below stays inside 21..87.
ADAPTIVE = {
    "canvas": 108.0,
    "outer": (54.0, 54.0, 24.0),
    "cut": (63.0, 46.0, 22.0),
    "star": (73.5, 35.0, 6.2, 2.55),
}

# The status bar icon is a separate, bolder drawing: at 24dp the adaptive
# artwork would be too small to read.
STATUS = {
    "canvas": 24.0,
    "outer": (11.5, 12.0, 8.5),
    "cut": (15.0, 9.5, 7.5),
    "star": (18.8, 7.0, 2.2, 0.9),
}

BACKGROUND_STOPS = ("#0B132B", "#1C2541", "#243657")
GOLD_STOPS = ("#F3D27A", "#DDB34F", "#C6972E")

DENSITIES = {
    "mdpi": 48,
    "hdpi": 72,
    "xhdpi": 96,
    "xxhdpi": 144,
    "xxxhdpi": 192,
}


def _hex(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))


def _star_points(cx: float, cy: float, outer: float, inner: float) -> list[tuple[float, float]]:
    points = []
    for index in range(10):
        angle = math.radians(-90.0 + index * 36.0)
        radius = outer if index % 2 == 0 else inner
        points.append((cx + radius * math.cos(angle), cy + radius * math.sin(angle)))
    return points


def _circle_intersections(c1: tuple[float, float, float], c2: tuple[float, float, float]):
    x1, y1, r1 = c1
    x2, y2, r2 = c2
    dx, dy = x2 - x1, y2 - y1
    distance = math.hypot(dx, dy)
    if distance == 0 or distance > r1 + r2 or distance < abs(r1 - r2):
        raise ValueError("circles do not have the two intersections this mark needs")
    a = (r1 * r1 - r2 * r2 + distance * distance) / (2.0 * distance)
    h = math.sqrt(max(0.0, r1 * r1 - a * a))
    base_x = x1 + a * dx / distance
    base_y = y1 + a * dy / distance
    perp_x, perp_y = -dy / distance, dx / distance
    return (
        (base_x + h * perp_x, base_y + h * perp_y),
        (base_x - h * perp_x, base_y - h * perp_y),
    )


def _crescent_path(geometry: dict) -> tuple[str, list[tuple[float, float]]]:
    (x1, y1, r1), (x2, y2, r2) = geometry["outer"], geometry["cut"]
    first, second = _circle_intersections((x1, y1, r1), (x2, y2, r2))
    # The first intersection sits above/left of the second in this geometry.
    top = min((first, second), key=lambda point: point[1])
    bottom = max((first, second), key=lambda point: point[1])
    path = (
        f"M {top[0]:.3f},{top[1]:.3f} "
        f"A {r1:.3f},{r1:.3f} 0 1,0 {bottom[0]:.3f},{bottom[1]:.3f} "
        f"A {r2:.3f},{r2:.3f} 0 0,1 {top[0]:.3f},{top[1]:.3f} Z"
    )
    return path, _star_points(*geometry["star"])


def _star_path(points: list[tuple[float, float]]) -> str:
    return "M " + " L ".join(f"{x:.3f},{y:.3f}" for x, y in points) + " Z"


def _vector_foreground() -> str:
    crescent, star = _crescent_path(ADAPTIVE)
    star_path = _star_path(star)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_salah_icons.py. Do not hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="{crescent}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="30"
                android:startY="30"
                android:endX="80"
                android:endY="80">
                <item android:offset="0" android:color="{GOLD_STOPS[0]}" />
                <item android:offset="1" android:color="{GOLD_STOPS[1]}" />
            </gradient>
        </aapt:attr>
    </path>
    <path
        android:fillColor="{GOLD_STOPS[0]}"
        android:pathData="{star_path}" />
</vector>
"""


def _vector_monochrome() -> str:
    crescent, star = _crescent_path(ADAPTIVE)
    star_path = _star_path(star)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_salah_icons.py. Do not hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{crescent}" />
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{star_path}" />
</vector>
"""


def _vector_status() -> str:
    crescent, star = _crescent_path(STATUS)
    star_path = _star_path(star)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_salah_icons.py. Do not hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{crescent}" />
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{star_path}" />
</vector>
"""


def _gradient(size: int, stops: tuple[str, str, str]) -> Image.Image:
    """A smooth diagonal three-stop gradient, at working resolution."""
    editor = Image.new("RGB", (2, 2))
    start, middle, end = (Image.new("RGB", (1, 1), _hex(stop)) for stop in stops)
    editor.paste(start, (0, 0))
    editor.paste(middle, (1, 0))
    editor.paste(middle, (0, 1))
    editor.paste(end, (1, 1))
    return editor.resize((size, size), Image.Resampling.BICUBIC)


def _foreground_mask(size: int, geometry: dict) -> Image.Image:
    scale = size / geometry["canvas"]
    mask = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(mask)

    def ellipse(circle, fill):
        cx, cy, radius = circle
        draw.ellipse(
            ((cx - radius) * scale, (cy - radius) * scale,
             (cx + radius) * scale, (cy + radius) * scale),
            fill=fill,
        )

    ellipse(geometry["outer"], 255)
    ellipse(geometry["cut"], 0)
    star = _star_points(*geometry["star"])
    draw.polygon([(x * scale, y * scale) for x, y in star], fill=255)
    return mask


def _icon(size: int, round_icon: bool) -> Image.Image:
    # Supersample so the curves and star tips stay clean at 48px.
    working = size * 4
    background = _gradient(working, BACKGROUND_STOPS)
    mask = _foreground_mask(working, ADAPTIVE)
    gold = _gradient(working, GOLD_STOPS)

    if round_icon:
        circle = Image.new("L", (working, working), 0)
        ImageDraw.Draw(circle).ellipse((0, 0, working - 1, working - 1), fill=255)
        background.putalpha(circle)
        mask = ImageChops.multiply(mask, circle)

    foreground = Image.new("RGBA", (working, working), (0, 0, 0, 0))
    foreground.paste(gold, (0, 0), mask)
    icon = Image.alpha_composite(background.convert("RGBA"), foreground)
    return icon.resize((size, size), Image.Resampling.LANCZOS)


def _write_webp(image: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, "WEBP", lossless=True, quality=100, method=6)


def main() -> None:
    drawable = RES / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)
    (drawable / "ic_launcher_foreground.xml").write_text(_vector_foreground())
    (drawable / "ic_launcher_monochrome.xml").write_text(_vector_monochrome())
    (drawable / "ic_stat_salah.xml").write_text(_vector_status())

    for density, size in DENSITIES.items():
        folder = RES / f"mipmap-{density}"
        folder.mkdir(parents=True, exist_ok=True)
        _write_webp(_icon(size, round_icon=False), folder / "ic_launcher.webp")
        _write_webp(_icon(size, round_icon=True), folder / "ic_launcher_round.webp")

    preview = _icon(512, round_icon=False)
    preview_path = ROOT / "build" / "salah-icon-preview.png"
    preview_path.parent.mkdir(parents=True, exist_ok=True)
    preview.save(preview_path)


if __name__ == "__main__":
    main()
